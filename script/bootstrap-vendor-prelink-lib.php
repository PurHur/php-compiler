<?php

declare(strict_types=1);

/**
 * M5 vendor prelink helpers (issue #1416).
 */

/** @var array<string, string> */
const BOOTSTRAP_VENDOR_PRELINK_PACKAGES = [
    'ircmaxell/php-cfg' => 'CFG + traversers',
    'ircmaxell/php-types' => 'TypeReconstructor',
    'ircmaxell/php-llvm' => 'LLVM FFI from PHP JIT',
];

/** Zend compile-driver deps materialized for cold-boot rebuild without composer (#2881). */
const BOOTSTRAP_VENDOR_PRELINK_DRIVER_PACKAGES = [
    'nikic/php-parser',
];

/**
 * @return list<string> repo-relative paths under vendor/<package>/lib
 */
function bootstrapVendorPrelinkSourcesRoot(string $root): string
{
    return $root.'/prelinked/bootstrap-vendor/sources';
}

/** Committed vendor lib/ snapshot for cold-boot AOT rebuild without composer (#2881). */
function bootstrapVendorPrelinkSourcesTreePresent(string $root): bool
{
    foreach (array_keys(BOOTSTRAP_VENDOR_PRELINK_PACKAGES) as $package) {
        $base = bootstrapVendorPrelinkSourcesRoot($root).'/'.$package;
        if (!is_dir($base.'/lib')) {
            return false;
        }
        if ('ircmaxell/php-llvm' === $package && !is_dir($base.'/ffi')) {
            return false;
        }
    }
    foreach (BOOTSTRAP_VENDOR_PRELINK_DRIVER_PACKAGES as $package) {
        if (!is_dir(bootstrapVendorPrelinkSourcesRoot($root).'/'.$package.'/lib')) {
            return false;
        }
    }

    return true;
}

function bootstrapVendorPrelinkLibPhpFiles(string $root, string $package): array
{
    $libDir = $root.'/vendor/'.$package.'/lib';
    if (!is_dir($libDir)) {
        $libDir = bootstrapVendorPrelinkSourcesRoot($root).'/'.$package.'/lib';
    }
    if (!is_dir($libDir)) {
        return [];
    }
    $paths = [];
    $it = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($libDir, FilesystemIterator::SKIP_DOTS)
    );
    foreach ($it as $file) {
        if (!$file->isFile() || !str_ends_with(strtolower($file->getFilename()), '.php')) {
            continue;
        }
        $paths[] = ltrim(str_replace('\\', '/', substr($file->getPathname(), strlen($root))), '/');
    }
    sort($paths);

    return $paths;
}

function bootstrapVendorPrelinkSlug(string $package): string
{
    return str_replace('/', '-', $package);
}

/**
 * Reuse link-time emit-helper or committed prelinked .o when native argv compile cannot (#3028).
 *
 * @return 'link-time'|'committed'|null
 */
function bootstrapVendorPrelinkCopySidecarFallback(string $root, string $slug, string $objectAbs): ?string
{
    $vendorShort = str_replace('-', '_', preg_replace('/^ircmaxell-/', '', $slug));
    $linktimeObject = $root.'/build/.m3_vendor_'.$vendorShort.'_prelink.o';
    if (is_file($linktimeObject)) {
        copy($linktimeObject, $objectAbs);

        return 'link-time';
    }
    $committedObject = $root.'/prelinked/bootstrap-vendor/'.$slug.'.o';
    if (is_file($committedObject)) {
        if (realpath($committedObject) !== realpath($objectAbs)) {
            copy($committedObject, $objectAbs);
        }

        return 'committed';
    }

    return null;
}

/**
 * @param list<string> $vendorRelPaths repo-relative vendor/*.php paths
 */
function bootstrapVendorPrelinkRenderBundle(
    string $package,
    string $role,
    array $vendorRelPaths,
    string $bundleRelPath
): string {
    $lines = [];
    $lines[] = '<?php';
    $lines[] = '';
    $lines[] = 'declare(strict_types=1);';
    $lines[] = '';
    $lines[] = '/**';
    $lines[] = ' * M5 vendor prelink bundle: `'.$package.'` ('.$role.').';
    $lines[] = ' * Auto-generated by `script/bootstrap-vendor-objects.php` — do not edit.';
    $lines[] = ' * Issue #1416.';
    $lines[] = ' */';
    $lines[] = '';
    foreach ($vendorRelPaths as $rel) {
        $lines[] = "require_once __DIR__.'/../../../{$rel}';";
    }
    $lines[] = '';
    $lines[] = "echo 'bootstrap-vendor-prelink ".bootstrapVendorPrelinkSlug($package)." OK\\n';";
    $lines[] = '';

    return implode("\n", $lines)."\n";
}

/**
 * @return array{version: int, generated_at: string, packages: array<string, array<string, mixed>>}
 */
function bootstrapVendorPrelinkEmptyManifest(string $root): array
{
    $packages = [];
    foreach (BOOTSTRAP_VENDOR_PRELINK_PACKAGES as $package => $role) {
        $slug = bootstrapVendorPrelinkSlug($package);
        $files = bootstrapVendorPrelinkLibPhpFiles($root, $package);
        $packages[$package] = [
            'role' => $role,
            'slug' => $slug,
            'bundle' => 'test/bootstrap-vendor-prelink/generated/'.$slug.'_bundle.php',
            'object' => 'prelinked/bootstrap-vendor/'.$slug.'.o',
            'archive' => 'prelinked/bootstrap-vendor/'.$slug.'.a',
            'php_files' => count($files),
            'status' => 'pending',
            'blocker' => null,
        ];
    }

    return [
        'version' => 1,
        'generated_at' => gmdate('c'),
        'packages' => $packages,
    ];
}

/**
 * @param array{version: int, generated_at: string, packages: array<string, array<string, mixed>>} $manifest
 */
function bootstrapVendorPrelinkWriteManifest(string $path, array $manifest): void
{
    $manifest['generated_at'] = gmdate('c');
    $json = json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n";
    $dir = dirname($path);
    if (!is_dir($dir)) {
        mkdir($dir, 0775, true);
    }
    file_put_contents($path, $json);
}

/**
 * @return array{version: int, generated_at: string, packages: array<string, array<string, mixed>>}|null
 */
function bootstrapVendorPrelinkReadManifest(string $path): ?array
{
    if (!is_file($path)) {
        return null;
    }
    $data = json_decode((string) file_get_contents($path), true);

    return is_array($data) ? $data : null;
}

/**
 * @return list<string> repo-relative object paths that exist on disk
 */
function bootstrapVendorPrelinkExistingObjects(string $root, array $manifest): array
{
    $found = [];
    foreach ($manifest['packages'] as $info) {
        if (!is_array($info)) {
            continue;
        }
        $rel = $info['object'] ?? '';
        if (!is_string($rel) || '' === $rel) {
            continue;
        }
        $abs = $root.'/'.$rel;
        if (is_file($abs)) {
            $found[] = $rel;
        }
    }

    return $found;
}

function bootstrapVendorPrelinkVendorTreePresent(string $root): bool
{
    foreach (array_keys(BOOTSTRAP_VENDOR_PRELINK_PACKAGES) as $package) {
        if (!is_dir($root.'/vendor/'.$package)) {
            return false;
        }
    }

    return is_file($root.'/vendor/autoload.php');
}

/**
 * M5 cold boot: verify committed bundles + manifest without regenerating from vendor/ (#2841).
 *
 * @param array{version: int, generated_at: string, packages: array<string, array<string, mixed>>} $manifest
 */
function bootstrapVendorPrelinkColdBootCheck(string $root, string $manifestPath, array $manifest): int
{
    if (!is_file($manifestPath)) {
        fwrite(STDERR, "Missing {$manifestPath}; cold boot requires committed manifest\n");

        return 1;
    }

    foreach (BOOTSTRAP_VENDOR_PRELINK_PACKAGES as $package => $role) {
        $slug = bootstrapVendorPrelinkSlug($package);
        $bundleRel = 'test/bootstrap-vendor-prelink/generated/'.$slug.'_bundle.php';
        $bundleAbs = $root.'/'.$bundleRel;
        if (!is_file($bundleAbs)) {
            fwrite(STDERR, "Missing bundle {$bundleRel}; cold boot requires committed vendor prelink bundles\n");

            return 1;
        }
        $bundleBody = (string) file_get_contents($bundleAbs);
        if (!str_contains($bundleBody, "vendor/{$package}/")) {
            fwrite(STDERR, "Bundle {$bundleRel} does not reference vendor/{$package} sources\n");

            return 1;
        }
        $expectedFiles = (int) ($manifest['packages'][$package]['php_files'] ?? 0);
        if ($expectedFiles <= 0) {
            fwrite(STDERR, "Manifest php_files for {$package} must be > 0 for cold boot\n");

            return 1;
        }
        $requireCount = substr_count($bundleBody, 'require_once');
        if ($requireCount < $expectedFiles) {
            fwrite(STDERR, "Bundle {$bundleRel} has {$requireCount} require_once lines; manifest expects {$expectedFiles}\n");

            return 1;
        }
    }

    return 0;
}

/**
 * Symlink vendor/ircmaxell/* → committed sources when composer tree is absent (#2881).
 *
 * @return string|null marker file when materialized (caller must cleanup)
 */
function bootstrapVendorPrelinkMaterializeVendorTree(string $root): ?string
{
    if (bootstrapVendorPrelinkVendorTreePresent($root)) {
        return null;
    }
    if (!bootstrapVendorPrelinkSourcesTreePresent($root)) {
        return null;
    }

    $marker = $root.'/build/bootstrap-vendor/.vendor-materialized';
    $sources = bootstrapVendorPrelinkSourcesRoot($root);
    $vendorIrc = $root.'/vendor/ircmaxell';
    if (!is_dir($root.'/vendor')) {
        mkdir($root.'/vendor', 0775, true);
    }
    if (!is_dir($vendorIrc)) {
        mkdir($vendorIrc, 0775, true);
    }

    $packages = [...array_keys(BOOTSTRAP_VENDOR_PRELINK_PACKAGES), ...BOOTSTRAP_VENDOR_PRELINK_DRIVER_PACKAGES];
    foreach ($packages as $package) {
        $target = $root.'/vendor/'.$package;
        $source = $sources.'/'.$package;
        $parent = dirname($target);
        if (!is_dir($parent)) {
            mkdir($parent, 0775, true);
        }
        if (is_link($target) || is_dir($target)) {
            if (is_link($target)) {
                unlink($target);
            } elseif (is_dir($target) && !str_starts_with(realpath($target) ?: '', realpath($source) ?: "\0")) {
                fwrite(STDERR, "bootstrap-vendor-prelink: vendor/{$package} exists and is not a symlink to sources\n");

                return null;
            } else {
                continue;
            }
        }
        $rel = bootstrapVendorPrelinkRelativePath($target, $source);
        if (!symlink($rel, $target)) {
            fwrite(STDERR, "bootstrap-vendor-prelink: failed to symlink vendor/{$package} → sources\n");

            return null;
        }
    }

    $markerDir = dirname($marker);
    if (!is_dir($markerDir)) {
        mkdir($markerDir, 0775, true);
    }
    file_put_contents($marker, gmdate('c')."\n");

    return $marker;
}

function bootstrapVendorPrelinkCleanupMaterializedVendorTree(string $root, ?string $marker): void
{
    if (null === $marker || !is_file($marker)) {
        return;
    }

    $packages = [...array_keys(BOOTSTRAP_VENDOR_PRELINK_PACKAGES), ...BOOTSTRAP_VENDOR_PRELINK_DRIVER_PACKAGES];
    foreach ($packages as $package) {
        $target = $root.'/vendor/'.$package;
        if (is_link($target)) {
            unlink($target);
        }
    }
    @rmdir($root.'/vendor/ircmaxell');
    @rmdir($root.'/vendor/nikic');
    if (is_dir($root.'/vendor') && [] === array_diff(scandir($root.'/vendor') ?: [], ['.', '..'])) {
        @rmdir($root.'/vendor');
    }
    @unlink($marker);
}

function bootstrapVendorPrelinkRelativePath(string $linkPath, string $targetPath): string
{
    $fromReal = realpath(dirname($linkPath)) ?: dirname($linkPath);
    $toReal = realpath($targetPath) ?: $targetPath;
    $fromParts = explode('/', str_replace('\\', '/', $fromReal));
    $toParts = explode('/', str_replace('\\', '/', $toReal));
    while ([] !== $fromParts && [] !== $toParts && $fromParts[0] === $toParts[0]) {
        array_shift($fromParts);
        array_shift($toParts);
    }
    $ups = array_fill(0, count($fromParts), '..');
    $rel = array_merge($ups, $toParts);

    return implode('/', $rel);
}

/**
 * Prefer actionable compile stderr/stdout over generic phase tails (#3049).
 *
 * @param list<string> $output
 */
function bootstrapVendorPrelinkExtractCompileFailureDetail(array $output): ?string
{
    $parseFailure = null;
    $typePhp = null;
    $runtimeException = null;
    $fatal = null;
    $missingAutoload = null;
    $lastNonEmpty = null;

    foreach ($output as $raw) {
        $line = trim((string) $raw);
        if ('' === $line) {
            continue;
        }
        $lastNonEmpty = $line;
        if (str_contains($line, 'Missing vendor autoload')) {
            $missingAutoload = $line;

            continue;
        }
        if (str_contains($line, 'parseAndCompile failure:')) {
            $parseFailure = $line;

            continue;
        }
        if (preg_match('/Type\\.php:\\d+/', $line)) {
            $typePhp = $line;

            continue;
        }
        if (str_contains($line, 'RuntimeException in ') || str_contains($line, 'Uncaught ')) {
            $runtimeException = $line;

            continue;
        }
        if (str_contains($line, 'PHP Fatal error:') || str_contains($line, 'Fatal error:')) {
            $fatal = $line;
        }
    }

    if (null !== $missingAutoload) {
        return $missingAutoload;
    }
    if (null !== $parseFailure) {
        return $parseFailure;
    }
    if (null !== $typePhp) {
        return $typePhp;
    }
    if (null !== $runtimeException) {
        return $runtimeException;
    }
    if (null !== $fatal) {
        return $fatal;
    }

    return $lastNonEmpty;
}

/**
 * AOT-compile vendor prelink bundles → prelinked .o (shared by warm and cold boot).
 *
 * Independent packages compile in parallel when PHP_COMPILER_COMPILE_JOBS>1.
 *
 * @param array{version: int, generated_at: string, packages: array<string, array<string, mixed>>} $manifest
 *
 * @return int number of failures
 */
/**
 * @param list<string>|null $onlyPackages restrict to these package names (e.g. cold-boot rebuild subset)
 */
/**
 * @param array{mode: 'native'|'zend', argv: list<string>}|null $invoker
 */
function bootstrapVendorPrelinkCompilePackages(
    string $root,
    array &$manifest,
    ?string $one = null,
    ?array $onlyPackages = null,
    ?array $invoker = null
): int {
    require_once __DIR__.'/compile-jobs-lib.php';

    $packages = [];
    foreach (BOOTSTRAP_VENDOR_PRELINK_PACKAGES as $package => $role) {
        if (null !== $onlyPackages && !in_array($package, $onlyPackages, true)) {
            continue;
        }
        if (null !== $one && $one !== $package && $one !== bootstrapVendorPrelinkSlug($package)) {
            continue;
        }
        $packages[] = $package;
    }

    if ([] === $packages) {
        return 0;
    }

    $jobs = php_compiler_compile_jobs();
    if ($jobs > 1 && count($packages) > 1) {
        fwrite(
            STDERR,
            'bootstrap-vendor-prelink: PHP_COMPILER_COMPILE_JOBS='.$jobs.' ('.count($packages)." packages)\n"
        );
    }

    if ($jobs <= 1 || count($packages) <= 1) {
        $failures = 0;
        foreach ($packages as $package) {
            $result = bootstrapVendorPrelinkCompileOnePackage($root, $package, $manifest, $invoker);
            bootstrapVendorPrelinkApplyCompileResult($manifest, $result, $failures);
        }

        return $failures;
    }

    $tasks = [];
    /** @var array<string, array{cmd: string}> $prepByPackage */
    $prepByPackage = [];
    $failures = 0;
    foreach ($packages as $package) {
        $prep = bootstrapVendorPrelinkPrepareCompileOnePackage($root, $package, $manifest, $invoker);
        if (null !== $prep['skip']) {
            bootstrapVendorPrelinkApplyCompileResult($manifest, $prep['skip'], $failures);
            continue;
        }
        $prepByPackage[$package] = ['cmd' => $prep['cmd']];
        $tasks[] = [
            'id' => $package,
            'cmd' => $prep['cmd'],
            'cwd' => $root,
        ];
    }

    if ([] === $tasks) {
        return $failures;
    }

    $results = php_compiler_run_parallel_commands($tasks, $jobs);
    foreach ($tasks as $task) {
        $package = $task['id'];
        $run = $results[$package] ?? ['exit' => 127, 'output' => 'missing parallel result'];
        $output = array_values(array_filter(explode("\n", str_replace("\r", '', $run['output']))));
        $result = bootstrapVendorPrelinkFinalizeCompileOnePackage(
            $root,
            $package,
            $manifest,
            (int) $run['exit'],
            $output,
            $prepByPackage[$package]['cmd'] ?? $task['cmd']
        );
        bootstrapVendorPrelinkApplyCompileResult($manifest, $result, $failures);
    }

    return $failures;
}

/**
 * @param array{version: int, generated_at: string, packages: array<string, array<string, mixed>>} $manifest
 *
 * @return array<string, mixed>
 */
function bootstrapVendorPrelinkPrepareCompileOnePackage(
    string $root,
    string $package,
    array $manifest,
    ?array $invoker = null
): array {
    $slug = bootstrapVendorPrelinkSlug($package);
    $bundleRel = $manifest['packages'][$package]['bundle'] ?? '';
    $bundleAbs = $root.'/'.$bundleRel;
    $objectRel = $manifest['packages'][$package]['object'] ?? '';
    $objectAbs = $root.'/'.$objectRel;
    $buildBase = $root.'/build/bootstrap-vendor/'.$slug;

    if (!is_string($bundleRel) || '' === $bundleRel || !is_file($bundleAbs)) {
        return [
            'skip' => [
                'package' => $package,
                'failed' => true,
                'status' => 'missing_bundle',
                'blocker' => null,
                'objectRel' => $objectRel,
                'buildBase' => $buildBase,
                'cmd' => '',
                'output' => [],
            ],
        ];
    }
    if (!is_string($objectRel) || '' === $objectRel) {
        return [
            'skip' => [
                'package' => $package,
                'failed' => true,
                'status' => 'compile_failed',
                'blocker' => 'missing object path in manifest',
                'objectRel' => $objectRel,
                'buildBase' => $buildBase,
                'cmd' => '',
                'output' => [],
            ],
        ];
    }

    if (!is_dir(dirname($buildBase))) {
        mkdir(dirname($buildBase), 0775, true);
    }
    if (!is_dir(dirname($objectAbs))) {
        mkdir(dirname($objectAbs), 0775, true);
    }

    @unlink($buildBase);
    @unlink($buildBase.'.o');

    return [
        'skip' => null,
        'cmd' => bootstrapVendorPrelinkBuildCompileCommand($root, $buildBase, $bundleAbs, $invoker),
        'buildBase' => $buildBase,
        'objectRel' => $objectRel,
        'objectAbs' => $objectAbs,
        'slug' => $slug,
    ];
}

/**
 * @param array{version: int, generated_at: string, packages: array<string, array<string, mixed>>} $manifest
 * @param list<string> $output
 *
 * @return array<string, mixed>
 */
function bootstrapVendorPrelinkFinalizeCompileOnePackage(
    string $root,
    string $package,
    array $manifest,
    int $code,
    array $output,
    string $cmd
): array {
    $slug = bootstrapVendorPrelinkSlug($package);
    $objectRel = $manifest['packages'][$package]['object'] ?? '';
    $objectAbs = $root.'/'.$objectRel;
    $buildBase = $root.'/build/bootstrap-vendor/'.$slug;
    $compileOut = $buildBase.'.o';
    $objectCandidate = $compileOut;

    if (0 === $code && is_file($objectCandidate)) {
        copy($objectCandidate, $objectAbs);

        return [
            'package' => $package,
            'failed' => false,
            'status' => 'object_ok',
            'blocker' => null,
            'objectRel' => $objectRel,
            'buildBase' => $buildBase,
            'cmd' => $cmd,
            'output' => $output,
            'message' => "OK {$package} → {$objectRel}",
        ];
    }
    if (0 === $code && !is_file($objectCandidate) && is_file($compileOut.'.o')) {
        copy($compileOut.'.o', $objectAbs);

        return [
            'package' => $package,
            'failed' => false,
            'status' => 'object_ok',
            'blocker' => null,
            'objectRel' => $objectRel,
            'buildBase' => $buildBase,
            'cmd' => $cmd,
            'output' => $output,
            'message' => "OK {$package} → {$objectRel} (native compile, legacy .o.o)",
        ];
    }
    if (0 === $code && !is_file($objectCandidate) && is_file($buildBase)) {
        copy($buildBase, $objectAbs);

        return [
            'package' => $package,
            'failed' => false,
            'status' => 'object_ok',
            'blocker' => null,
            'objectRel' => $objectRel,
            'buildBase' => $buildBase,
            'cmd' => $cmd,
            'output' => $output,
            'message' => "OK {$package} → {$objectRel} (native compile)",
        ];
    }

    $sidecarSource = bootstrapVendorPrelinkCopySidecarFallback($root, $slug, $objectAbs);
    if (null !== $sidecarSource) {
        $via = 'link-time' === $sidecarSource ? 'link-time vendor sidecar' : 'committed prelink';

        return [
            'package' => $package,
            'failed' => false,
            'status' => 'object_ok',
            'blocker' => null,
            'objectRel' => $objectRel,
            'buildBase' => $buildBase,
            'cmd' => $cmd,
            'output' => $output,
            'message' => "OK {$package} → {$objectRel} ({$via})",
        ];
    }

    $blocker = 0 !== $code
        ? 'compile exit '.$code.' (vendor bundle AOT — #1416, #2849)'
        : 'missing object file after compile';

    $logPath = $buildBase.'.log';
    file_put_contents($logPath, implode("\n", array_map('strval', $output))."\n");
    $firstActionable = bootstrapVendorPrelinkExtractCompileFailureDetail($output);
    if (null === $firstActionable && is_file($logPath)) {
        $logLines = file($logPath, FILE_IGNORE_NEW_LINES) ?: [];
        $firstActionable = bootstrapVendorPrelinkExtractCompileFailureDetail($logLines);
    }
    if (null !== $firstActionable && str_contains($firstActionable, 'Missing vendor autoload')) {
        $blocker = 'vendor prelink must not require composer autoload (#2849)';
    }
    if (null !== $firstActionable) {
        $blocker .= ' — '.$firstActionable;
    }

    return [
        'package' => $package,
        'failed' => true,
        'status' => 139 === $code ? 'compile_segfault' : 'compile_failed',
        'blocker' => $blocker,
        'objectRel' => $objectRel,
        'buildBase' => $buildBase,
        'cmd' => $cmd,
        'output' => $output,
        'logPath' => $logPath,
    ];
}

/**
 * @param array{version: int, generated_at: string, packages: array<string, array<string, mixed>>} $manifest
 *
 * @return array<string, mixed>
 */
function bootstrapVendorPrelinkCompileOnePackage(
    string $root,
    string $package,
    array $manifest,
    ?array $invoker = null
): array {
    $prep = bootstrapVendorPrelinkPrepareCompileOnePackage($root, $package, $manifest, $invoker);
    if (null !== $prep['skip']) {
        return $prep['skip'];
    }

    $output = [];
    exec($prep['cmd'], $output, $code);

    return bootstrapVendorPrelinkFinalizeCompileOnePackage(
        $root,
        $package,
        $manifest,
        (int) $code,
        $output,
        $prep['cmd']
    );
}

/**
 * @param array{version: int, generated_at: string, packages: array<string, array<string, mixed>>} $manifest
 * @param array<string, mixed> $result
 */
function bootstrapVendorPrelinkApplyCompileResult(array &$manifest, array $result, int &$failures): void
{
    $package = (string) ($result['package'] ?? '');
    if ('' === $package) {
        return;
    }
    $manifest['packages'][$package]['status'] = (string) ($result['status'] ?? 'compile_failed');
    $manifest['packages'][$package]['blocker'] = $result['blocker'] ?? null;

    if (!empty($result['failed'])) {
        ++$failures;
        $blocker = (string) ($result['blocker'] ?? 'compile failed');
        fwrite(STDERR, "FAIL {$package}: {$blocker}\n");
        if ('' !== (string) ($result['cmd'] ?? '')) {
            fwrite(STDERR, '  cmd: '.(string) $result['cmd']."\n");
        }
        if (isset($result['logPath'])) {
            fwrite(STDERR, '  log: '.(string) $result['logPath']."\n");
        }
        $output = $result['output'] ?? [];
        if (is_array($output) && [] !== $output) {
            $tail = array_slice($output, -60);
            fwrite(STDERR, "  tail:\n");
            foreach ($tail as $line) {
                fwrite(STDERR, '    '.(string) $line."\n");
            }
        }

        return;
    }

    $message = (string) ($result['message'] ?? ('OK '.$package));
    fwrite(STDOUT, $message."\n");
}

/**
 * Cold boot: reuse committed .o or AOT-rebuild missing ones via sources snapshot (#2841, #2881).
 *
 * @param array{version: int, generated_at: string, packages: array<string, array<string, mixed>>} $manifest
 */
function bootstrapVendorPrelinkColdBootCompile(string $root, string $manifestPath, array &$manifest, ?string $one = null): int
{
    $needsRebuild = [];
    foreach (BOOTSTRAP_VENDOR_PRELINK_PACKAGES as $package => $role) {
        if (null !== $one && $one !== $package && $one !== bootstrapVendorPrelinkSlug($package)) {
            continue;
        }
        $objectRel = $manifest['packages'][$package]['object'] ?? '';
        if (!is_string($objectRel) || '' === $objectRel) {
            $needsRebuild[] = $package;
            continue;
        }
        if (!is_file($root.'/'.$objectRel)) {
            $needsRebuild[] = $package;
        }
    }

    if ([] === $needsRebuild) {
        foreach (BOOTSTRAP_VENDOR_PRELINK_PACKAGES as $package => $role) {
            if (null !== $one && $one !== $package && $one !== bootstrapVendorPrelinkSlug($package)) {
                continue;
            }
            $objectRel = $manifest['packages'][$package]['object'] ?? '';
            $manifest['packages'][$package]['status'] = 'object_ok';
            $manifest['packages'][$package]['blocker'] = null;
            fwrite(STDOUT, "OK {$package} → {$objectRel} (cold boot: committed prelink)\n");
        }
        bootstrapVendorPrelinkWriteManifest($manifestPath, $manifest);
        fwrite(STDOUT, "bootstrap-vendor-objects: cold boot — all prelink objects from committed artifacts\n");

        return 0;
    }

    if (!bootstrapVendorPrelinkSourcesTreePresent($root)) {
        foreach ($needsRebuild as $package) {
            $objectRel = $manifest['packages'][$package]['object'] ?? '';
            $manifest['packages'][$package]['status'] = 'missing_object';
            $manifest['packages'][$package]['blocker'] = 'cold boot: committed '.$objectRel.' missing (no sources snapshot — #2881)';
        }
        bootstrapVendorPrelinkWriteManifest($manifestPath, $manifest);
        fwrite(STDERR, 'bootstrap-vendor-objects: '.count($needsRebuild).' package(s) missing prelink .o and sources snapshot (vendor/ absent)'."\n");

        return 1;
    }

    $llvm = getenv('PHP_COMPILER_LLVM_PATH') ?: '';
    if ('' === $llvm || !is_file($llvm.'/libLLVM-9.so.1')) {
        fwrite(STDERR, "bootstrap-vendor-objects: LLVM 9 required to rebuild missing prelink .o (set PHP_COMPILER_LLVM_PATH)\n");

        return 2;
    }

    $marker = bootstrapVendorPrelinkMaterializeVendorTree($root);
    if (null === $marker) {
        fwrite(STDERR, "bootstrap-vendor-objects: failed to materialize vendor sources for cold-boot rebuild\n");

        return 1;
    }

    putenv('PHP_COMPILER_SELFHOST_AOT=0');
    putenv('PHP_COMPILER_VENDOR_PRELINK=1');
    putenv('PHP_COMPILER_KEEP_OBJECT_FILE=1');

    bootstrapVendorPrelinkEnsureDriverSidecars($root);

    $compileInvoker = bootstrapVendorPrelinkResolveCompileInvoker($root);
    if (
        'zend' === $compileInvoker['mode']
        && '1' !== (string) getenv('BOOTSTRAP_M5_VENDOR_ALLOW_ZEND')
    ) {
        fwrite(
            STDERR,
            "bootstrap-vendor-objects: cold boot requires native compile driver (no Zend in loop)\n"
        );
        fwrite(
            STDERR,
            "bootstrap-vendor-objects: no compiled driver under build/ (expected one of selfhost-compile-driver, selfhost-native-compile-driver, bin-compile-aot)\n"
        );
        fwrite(
            STDERR,
            "bootstrap-vendor-objects: one-time bootstrap:\n"
        );
        fwrite(
            STDERR,
            "  ./script/docker-exec.sh -- bash -lc 'make bootstrap-selfhost-driver-smoke'\n"
        );
        fwrite(
            STDERR,
            "bootstrap-vendor-objects: or set BOOTSTRAP_M5_VENDOR_ALLOW_ZEND=1 to permit gen-0 fallback (NOT M5)\n"
        );
        bootstrapVendorPrelinkCleanupMaterializedVendorTree($root, $marker);
        bootstrapVendorPrelinkWriteManifest($manifestPath, $manifest);

        return 1;
    }
    fwrite(
        STDERR,
        'bootstrap-vendor-objects: cold-boot rebuild invoker='.$compileInvoker['mode']
        .' ('.($compileInvoker['argv'][0] ?? 'unknown').") (#2881)\n"
    );
    fwrite(STDERR, "bootstrap-vendor-objects: materialized vendor/ from prelinked/bootstrap-vendor/sources\n");

    $failures = 0;
    foreach (BOOTSTRAP_VENDOR_PRELINK_PACKAGES as $package => $role) {
        if (null !== $one && $one !== $package && $one !== bootstrapVendorPrelinkSlug($package)) {
            continue;
        }
        $objectRel = $manifest['packages'][$package]['object'] ?? '';
        $objectAbs = is_string($objectRel) && '' !== $objectRel ? $root.'/'.$objectRel : '';
        if ('' !== $objectAbs && is_file($objectAbs) && !in_array($package, $needsRebuild, true)) {
            $manifest['packages'][$package]['status'] = 'object_ok';
            $manifest['packages'][$package]['blocker'] = null;
            fwrite(STDOUT, "OK {$package} → {$objectRel} (cold boot: committed prelink)\n");
            continue;
        }
    }

    $failures += bootstrapVendorPrelinkCompilePackages($root, $manifest, $one, $needsRebuild);

    if (
        $failures > 0
        && bootstrapVendorPrelinkFailuresAreNativeParseSpine($manifest, $needsRebuild)
    ) {
        fwrite(
            STDERR,
            "bootstrap-vendor-objects: native driver parse spine null; cold-boot Zend rebuild (#2967)\n"
        );
        putenv('BOOTSTRAP_M5_VENDOR_ALLOW_ZEND=1');
        $zendInvoker = [
            'mode' => 'zend',
            'argv' => [PHP_BINARY, $root.'/bin/compile.php'],
        ];
        $failures = bootstrapVendorPrelinkCompilePackages($root, $manifest, $one, $needsRebuild, $zendInvoker);
    }

    bootstrapVendorPrelinkCleanupMaterializedVendorTree($root, $marker);
    bootstrapVendorPrelinkWriteManifest($manifestPath, $manifest);

    if ($failures > 0) {
        fwrite(STDERR, "bootstrap-vendor-objects: {$failures} package(s) failed cold-boot rebuild (manifest updated)\n");

        return 1;
    }

    fwrite(STDOUT, "bootstrap-vendor-objects: cold boot — prelink objects OK (committed + rebuilt)\n");

    return 0;
}

/**
 * Link-time vendor .o sidecars for M3 emit-helper (inventory driver — #3036).
 *
 * Built by bootstrap-selfhost-driver-host-compile.sh with BOOTSTRAP_M5_DRIVER_HOST_FULL_CLI=1.
 */
function bootstrapVendorPrelinkEnsureDriverSidecars(string $root): bool
{
    if (is_file($root.'/build/.m3_vendor_php_cfg_prelink.o')) {
        return true;
    }
    $script = $root.'/script/bootstrap-selfhost-driver-host-compile.sh';
    if (!is_file($script)) {
        fwrite(STDERR, "bootstrap-vendor-objects: missing {$script} (cannot build vendor sidecars)\n");

        return false;
    }
    $llvm = getenv('PHP_COMPILER_LLVM_PATH') ?: '';
    if ('' === $llvm || !is_file($llvm.'/libLLVM-9.so.1')) {
        fwrite(STDERR, "bootstrap-vendor-objects: LLVM 9 required to build vendor emit sidecars\n");

        return false;
    }
    fwrite(STDERR, "bootstrap-vendor-objects: building M5 vendor emit sidecars (BOOTSTRAP_M5_DRIVER_HOST_FULL_CLI=1 — #3036)\n");
    putenv('BOOTSTRAP_M5_DRIVER_HOST_FULL_CLI=1');
    $cmd = 'bash '.escapeshellarg($script);
    passthru($cmd, $code);

    return 0 === $code && is_file($root.'/build/.m3_vendor_php_cfg_prelink.o');
}

/**
 * Resolve gen-0 vendor prelink AOT invoker: compiled driver when present, else Zend php bin/compile.php (#2842, #2849).
 *
 * @return array{mode: 'native'|'zend', argv: list<string>}
 */
function bootstrapVendorPrelinkResolveCompileInvoker(string $root): array
{
    if ('1' === (string) getenv('BOOTSTRAP_GEN0_ZEND_ONLY')) {
        return [
            'mode' => 'zend',
            'argv' => [PHP_BINARY, $root.'/bin/compile.php'],
        ];
    }

    foreach ([
        $root.'/build/bin-compile-aot-inventory',
        $root.'/build/bin-compile-aot',
        $root.'/build/selfhost-native-compile-driver',
        $root.'/build/selfhost-helloworld-compile',
        $root.'/build/selfhost-compile-driver',
    ] as $candidate) {
        if (is_executable($candidate)) {
            return [
                'mode' => 'native',
                'argv' => [$candidate],
            ];
        }
    }

    return [
        'mode' => 'zend',
        'argv' => [PHP_BINARY, $root.'/bin/compile.php'],
    ];
}

/** Shell command for vendor bundle AOT → .o (env + driver + -o + entry). */
/** @param list<string> $packages */
function bootstrapVendorPrelinkFailuresAreNativeParseSpine(array $manifest, array $packages): bool
{
    if ([] === $packages) {
        return false;
    }
    foreach ($packages as $package) {
        $blocker = (string) ($manifest['packages'][$package]['blocker'] ?? '');
        if (
            !str_contains($blocker, 'parseAndCompile returned null')
            && !str_contains($blocker, 'native emit failed at phase=parseAndCompile')
        ) {
            return false;
        }
    }

    return true;
}

/**
 * @return list<string> repo-relative paths under prelinked/bootstrap-vendor/sources only
 */
function bootstrapVendorPrelinkSourcesOnlyPhpFiles(string $root, string $package): array
{
    $libDir = bootstrapVendorPrelinkSourcesRoot($root).'/'.$package.'/lib';
    if (!is_dir($libDir)) {
        return [];
    }
    $paths = [];
    $it = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($libDir, FilesystemIterator::SKIP_DOTS)
    );
    foreach ($it as $file) {
        if (!$file->isFile() || !str_ends_with(strtolower($file->getFilename()), '.php')) {
            continue;
        }
        $paths[] = ltrim(str_replace('\\', '/', substr($file->getPathname(), strlen($root))), '/');
    }
    sort($paths);

    return $paths;
}

function bootstrapVendorPrelinkSha256File(string $path): ?string
{
    if (!is_file($path)) {
        return null;
    }
    $hash = hash_file('sha256', $path);

    return is_string($hash) && '' !== $hash ? $hash : null;
}

function bootstrapVendorPrelinkSourcesContentHash(string $root, string $package): ?string
{
    $paths = bootstrapVendorPrelinkSourcesOnlyPhpFiles($root, $package);
    if ([] === $paths) {
        return null;
    }
    $ctx = hash_init('sha256');
    foreach ($paths as $rel) {
        hash_update($ctx, $rel."\0");
        hash_update($ctx, (string) file_get_contents($root.'/'.$rel));
    }

    return hash_final($ctx);
}

/**
 * Native rebuild audit for one vendor package (#8718).
 *
 * @param array{mode: 'native'|'zend', argv: list<string>} $invoker
 *
 * @return array{
 *   status: 'match'|'drift'|'rebuild_failed'|'missing_committed'|'missing_bundle'|'missing_sources',
 *   package: string,
 *   slug: string,
 *   committed_hash: ?string,
 *   rebuilt_hash: ?string,
 *   sources_hash: ?string,
 *   blocker: ?string,
 *   cmd: ?string
 * }
 */
function bootstrapVendorPrelinkAuditPackage(
    string $root,
    string $package,
    array $invoker,
    string $auditDir
): array {
    $slug = bootstrapVendorPrelinkSlug($package);
    $result = [
        'status' => 'rebuild_failed',
        'package' => $package,
        'slug' => $slug,
        'committed_hash' => null,
        'rebuilt_hash' => null,
        'sources_hash' => bootstrapVendorPrelinkSourcesContentHash($root, $package),
        'blocker' => null,
        'cmd' => null,
    ];
    if ([] === bootstrapVendorPrelinkSourcesOnlyPhpFiles($root, $package)) {
        $result['status'] = 'missing_sources';

        return $result;
    }
    $manifestPath = $root.'/prelinked/bootstrap-vendor/manifest.json';
    $manifest = bootstrapVendorPrelinkReadManifest($manifestPath) ?? bootstrapVendorPrelinkEmptyManifest($root);
    $bundleRel = (string) ($manifest['packages'][$package]['bundle'] ?? '');
    $bundleAbs = '' !== $bundleRel ? $root.'/'.$bundleRel : '';
    if ('' === $bundleRel || !is_file($bundleAbs)) {
        $result['status'] = 'missing_bundle';

        return $result;
    }
    $committedRel = (string) ($manifest['packages'][$package]['object'] ?? '');
    $committedAbs = '' !== $committedRel ? $root.'/'.$committedRel : '';
    if ('' === $committedRel || !is_file($committedAbs)) {
        $result['status'] = 'missing_committed';

        return $result;
    }
    $result['committed_hash'] = bootstrapVendorPrelinkSha256File($committedAbs);

    if (!is_dir($auditDir)) {
        mkdir($auditDir, 0775, true);
    }
    $buildBase = $auditDir.'/'.$slug;
    $rebuiltAbs = $buildBase.'.o';
    @unlink($buildBase);
    @unlink($rebuiltAbs);

    $cmd = bootstrapVendorPrelinkBuildCompileCommand($root, $buildBase, $bundleAbs, $invoker);
    $result['cmd'] = $cmd;
    $output = [];
    exec($cmd, $output, $code);
    $objectCandidate = $rebuiltAbs;
    if (0 === $code && !is_file($objectCandidate) && is_file($buildBase)) {
        copy($buildBase, $rebuiltAbs);
    }
    if (0 === $code && !is_file($objectCandidate) && is_file($rebuiltAbs.'.o')) {
        copy($rebuiltAbs.'.o', $rebuiltAbs);
    }
    if (0 !== $code || !is_file($rebuiltAbs)) {
        $blocker = 0 !== $code
            ? 'compile exit '.$code
            : 'missing rebuilt object after compile';
        $detail = bootstrapVendorPrelinkExtractCompileFailureDetail($output);
        if (null !== $detail) {
            $blocker .= ' — '.$detail;
        }
        $result['status'] = 'rebuild_failed';
        $result['blocker'] = $blocker;

        return $result;
    }

    $result['rebuilt_hash'] = bootstrapVendorPrelinkSha256File($rebuiltAbs);
    if ($result['committed_hash'] === $result['rebuilt_hash']) {
        $result['status'] = 'match';
    } else {
        $result['status'] = 'drift';
    }

    return $result;
}

/**
 * @param array{mode: 'native'|'zend', argv: list<string>}|null $invoker
 */
function bootstrapVendorPrelinkBuildCompileCommand(
    string $root,
    string $buildBase,
    string $bundleAbs,
    ?array $invoker = null
): string {
    $inv = $invoker ?? bootstrapVendorPrelinkResolveCompileInvoker($root);
    $argv = array_map('escapeshellarg', $inv['argv']);
    // Native argv driver copies link-time vendor .o sidecar to -o; use .o path (#3036).
    $compileOut = $buildBase.'.o';

    return 'PHP_COMPILER_VENDOR_PRELINK=1 PHP_COMPILER_SELFHOST_AOT=0 PHP_COMPILER_KEEP_OBJECT_FILE=1 '
        .' PHP_COMPILER_M3_EMIT_HELPER_SPINE=1 '
        .implode(' ', $argv)
        .' -o '.escapeshellarg($compileOut)
        .' '.escapeshellarg($bundleAbs)
        .' 2>&1';
}
